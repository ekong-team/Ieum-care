ALL_GROUPS = list(RULES) + ["미분류"]


def classification_table():
    rows = []
    for group, (role, reason, caution, industries) in RULES.items():
        for industry in industries:
            rows.append({"업종": industry, "업종그룹": group, "해석역할": role,
                         "분류근거": reason, "주의사항": caution, "분류버전": VERSION})
    table = pd.DataFrame(rows)
    if table["업종"].duplicated().any():
        raise ValueError("업종 분류표에 중복 배정이 있습니다.")
    return table


def classify_industries(values):
    mapping = classification_table().set_index("업종")["업종그룹"]
    return values.map(mapping).fillna("미분류")

